import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const schemaDir = resolve(here, '../../docs/workbench/schema')
const output = resolve(here, '../src/generated/contract.ts')
const names = ['envelope', 'value', 'structure', 'run', 'paper', 'diagnostics', 'workspace', 'compare', 'parameters', 'export-preview', 'explain']
const schemas = Object.fromEntries(await Promise.all(names.map(async name => [name, JSON.parse(await readFile(resolve(schemaDir, `${name}.schema.json`), 'utf8'))])))
const pascal = value => value.replace(/(^|[-_])([a-z])/g, (_, __, letter) => letter.toUpperCase())
const typeName = (file, def) => `${pascal(file)}${def ? pascal(def) : ''}`

function reference(ref, file) {
  const [path, pointer = ''] = ref.split('#')
  const target = path ? path.replace(/\.schema\.json$/, '') : file
  if (!schemas[target]) throw new Error(`Unknown schema reference: ${ref}`)
  if (!pointer) return typeName(target)
  const parts = pointer.split('/').filter(Boolean)
  if (parts.length !== 2 || parts[0] !== '$defs') throw new Error(`Unsupported schema pointer: ${ref}`)
  return typeName(target, parts[1])
}

function emit(schema, file) {
  if (schema.$ref) return reference(schema.$ref, file)
  if ('const' in schema) return JSON.stringify(schema.const)
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ')
  if (schema.oneOf || schema.anyOf) return `(${(schema.oneOf ?? schema.anyOf).map(item => emit(item, file)).join(' | ')})`
  if (schema.allOf) {
    // The workbench documents overlay envelope.data through allOf.
    const inherited = schema.allOf.map(item => emit(item, file))
    if (schema.properties?.data && inherited.includes('Envelope')) inherited[0] = "Omit<Envelope, 'data'>"
    const own = schema.properties ? emit({ type: 'object', required: schema.required ?? (schema.properties.data ? ['data'] : []), properties: schema.properties, additionalProperties: schema.additionalProperties }, file) : null
    return `(${[...inherited, own].filter(Boolean).join(' & ')})`
  }
  const kinds = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  if (kinds.length > 1) return `(${kinds.map(type => emit({ ...schema, type }, file)).join(' | ')})`
  switch (kinds[0]) {
    case 'null': return 'null'
    case 'boolean': return 'boolean'
    case 'string': return 'string'
    case 'integer':
    case 'number': return 'number'
    case 'array': {
      if (schema.prefixItems) return `[${schema.prefixItems.map(item => emit(item, file)).join(', ')}]`
      return `Array<${schema.items ? emit(schema.items, file) : 'unknown'}>`
    }
    case 'object': {
      const properties = Object.entries(schema.properties ?? {})
      const required = new Set(schema.required ?? [])
      const fields = properties.map(([key, value]) => `${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${emit(value, file)}`)
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        if (fields.length) throw new Error(`Mixed named and dynamic properties in ${file}`)
        return `Record<string, ${emit(schema.additionalProperties, file)}>`
      }
      return fields.length ? `{ ${fields.join('; ')} }` : 'Record<string, unknown>'
    }
    default: return 'unknown'
  }
}

const source = [
  '// Generated from docs/workbench/schema/*.schema.json. Run npm run types:generate.',
  '// Do not edit this file by hand; JSON Schema is the wire contract.',
  '',
  ...names.flatMap(name => {
    const schema = schemas[name]
    return [
      `export type ${typeName(name)} = ${emit(schema, name)}`,
      ...Object.entries(schema.$defs ?? {}).map(([key, value]) => `export type ${typeName(name, key)} = ${emit(value, name)}`),
      '',
    ]
  }),
].join('\n')

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8').catch(() => '')
  if (current !== source) {
    console.error('Generated contract types are stale. Run npm run types:generate.')
    process.exitCode = 1
  }
} else {
  await mkdir(dirname(output), { recursive: true })
  await writeFile(output, source)
  console.log(`Generated ${output}`)
}
